#!/usr/bin/env python3
"""
generate_metrics_doc.py — writes METRICS.md, the data dictionary of every headline column on Master and A1-A4 (Jake,
2026-10-11, D1). Generated, not hand-written, so it matches the code:

  * THE COLUMNS come from a real build (build_workbook on an empty store, every column spec captured as written) —
    Master's columns and every BOLD headline on A1-A4, plus the supporting columns export_snapshot carries.
  * THE MEANING comes from metrics_dictionary.ENTRIES (definition, formula, window, unit, counts / excludes, the
    decision and its date); THE INPUTS' labels, units and source tiers from config.METRICS.
  * THE PER-PROJECT BASES (circulating used, total supply source, buyback route, burn series, issuance basis,
    absorption emissions, unlock stocks) are read from config's own functions.

    python generate_metrics_doc.py            write METRICS.md
    python generate_metrics_doc.py --check    exit 1 if METRICS.md differs from what would be written, or a headline
                                              has no dictionary entry (the test runs this)
"""
from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "METRICS.md"
TABS = (("Master", "Master"), ("A1", "A1 — Infrastructure"), ("A2", "A2 — Coordination"),
        ("A3", "A3 — Revenue buyback"), ("A4", "A4 — Permanent burn"), ("CP", "CP — Comparability (Phase 2)"))
SKIP = {"Project", "Symbol"}
TIER_NAMES = {1: "free API", 2: "contract / chain read", 3: "rendered page / manual"}


def captured_columns() -> list[tuple[str, str, bool, str | None]]:
    """[(sheet title, header, bold, metric)] for every column build_workbook writes, from a build on an empty store."""
    import pandas as pd
    import build_workbook as bw
    import store as sm
    cap: list = []
    orig = bw._write_table

    def wrap(ws, R, projects, specs, *a, **k):
        for s in specs:
            meta = s[5] if len(s) > 5 else {}
            cap.append((ws.title, s[0], bool(s[4]) if len(s) > 4 else False, meta.get("metric")))
        return orig(ws, R, projects, specs, *a, **k)
    bw._write_table = wrap
    try:
        with tempfile.TemporaryDirectory() as tmp:
            db = Path(tmp) / "metrics.db"
            sm.Store(str(db)).close()
            saved = sm.DB_PATH
            sm.DB_PATH = str(db)
            # CLOSED BEFORE THE TEMPORARY DIRECTORY GOES (Jake's run on e4e50b0, 2026-10-12 item 1): Windows refuses to
            # delete a database file a connection still holds open (PermissionError, WinError 32)
            st = sm.Store(str(db))
            try:
                bw.build_workbook(st, Path(tmp) / "wb.xlsx", asof=pd.Timestamp("2026-10-11"))
            finally:
                st.close()
                sm.DB_PATH = saved
    finally:
        bw._write_table = orig
    return cap


def headlines(cap) -> dict:
    """{tab prefix: [(header, metric)]} — Master's columns, the bold A-tab headlines, the extra snapshot columns."""
    import build_workbook as bw
    out: dict = {pre: [] for pre, _t in TABS}
    for title, head, bold, metric in cap:
        pre = "Master" if title == "Master" else title[:2]
        if pre not in out or head in SKIP:
            continue
        if pre == "Master" or bold or head in bw.EXTRA_SNAPSHOT_HEADERS:
            if head not in [h for h, _m in out[pre]]:
                out[pre].append((head, metric))
    return out


def missing_entries(heads: dict) -> list[str]:
    import metrics_dictionary as md
    return [f"{pre}: {h}" for pre, hs in heads.items() for h, _m in hs if md.entry_for(h) is None]


def _metric_line(m: str) -> str:
    import config
    spec = config.METRICS.get(m)
    if not spec:
        return f"`{m}` (a build-time view)"
    tiers = ", ".join(f"{t} {TIER_NAMES.get(t, '')}".strip() for t in spec.get("tiers") or [])
    return f"`{m}` — {spec['label']} ({spec.get('kind')}, {spec.get('unit')}; tiers in order: {tiers or '—'})"


def render(heads: dict) -> str:
    import config
    import metrics_dictionary as md
    L = ["# METRICS — the data dictionary",
         "",
         "GENERATED by `python generate_metrics_doc.py` from the build's own column list, `metrics_dictionary.py` and "
         "`config.py`. Do not edit by hand: change the code or the dictionary and regenerate (the test fails when this "
         "file is stale or a headline has no entry). One page per tab; the per-project bases at the end.",
         "", "## Conventions every column shares", ""]
    for name, text in md.CONVENTIONS:
        L.append(f"- **{name}.** {text}")
    for pre, title in TABS:
        L += ["", "---", "", f"## {title}", ""]
        for head, metric in heads[pre]:
            key, e = md.entry_for(head)
            L.append(f"### {head}")
            L.append("")
            L.append(f"- **What:** {e['what']}")
            L.append(f"- **Formula:** {e['formula']}")
            L.append(f"- **Window:** {e['window']} · **Unit:** {e['unit']}")
            if e.get("counts"):
                L.append(f"- **Counts:** {e['counts']}")
            if e.get("excludes"):
                L.append(f"- **Excludes:** {e['excludes']}")
            ins = list(dict.fromkeys(([metric] if metric else []) + list(e.get("inputs") or [])))
            if ins:
                L.append("- **Inputs (source tiers in priority order):**")
                L += [f"  - {_metric_line(m)}" for m in ins]
            for who, when, what in e.get("decided") or []:
                L.append(f"- **Decision:** {who}, {when} — {what}")
            L.append("")
    import trajectory
    T = config.TRAJECTORY
    L += ["---", "", "## Trajectory tab (theory layer, Phase 1)", "",
          f"Windows: {T['quarters']} consecutive trailing {T['period_days']}-day blocks (Q0 .. Q-{T['quarters'] - 1}); "
          f"the free backfills ask for {T['history_days']} days. Columns: " + " · ".join(trajectory.HEAD) + ".", "",
          "Every row's group and direction are declared (Jake's Phase 1 review 2026-10-12, items 5-6; nothing defaults "
          "to +1 — an undeclared row reads 'direction not declared'). The arrow follows the 4-quarter growth with "
          "quarters improved; QoQ is secondary text. Growth needs ≥ "
          f"{T['growth']['min_quarters']} quarters, all > 0, in one regime; an earliest quarter below "
          f"{T['growth']['new_share']:.0%} of the latest, or a mechanism that starts (older quarters reading 0) or a "
          "basis break inside the window, shows NEW since Q-x / STEP CHANGE at Q-x instead (item 4). A DIVERGENCE table "
          "per project sets the fundamentals' 4Q growth (revenue; tokens retired / burned) against price's (item 6).",
          "", "| Group | Row | Direction |", "|---|---|---|"]
    order = {g: i for i, g in enumerate(T["groups"])}
    for hid, (grp, d) in sorted(T["rows"].items(), key=lambda kv: (order.get(kv[1][0], 9), kv[0])):
        L.append(f"| {grp} | `{hid}` | {d:+d} |")
    L += ["", "| Benchmark | Rows | Target |", "|---|---|---|"]
    for b in T["benchmarks"]:
        prm = T["params"].get(b.get("target_param", ""), {})
        tgt = (b["target"] if "target" in b else
               f"{prm.get('value')} ({prm.get('source', '')})" if prm.get("value") is not None else
               f"stored `{prm.get('metric')}` ({prm.get('source', '')})")
        L.append(f"| {b['label']} | {', '.join(f'`{x}`' for x in b['on'])} | {tgt} |")
    L += ["", "History gaps: `python history_gaps.py` writes logs/history_gaps.csv for the 15 portfolio projects — "
          "earliest date, Q0..Q-3 coverage (Q-4 a bonus column), blocking reason, cheapest fix; series n/a by structure "
          "(no mechanism, issuance declared zero) are left out; `--run-fixes` runs the ones that need no new paid access.",
          ""]
    L += flow_statements()
    L += ["---", "", "## Per-project bases (from config)", "",
          "| Project | Archetypes | Circulating used | Total supply | Buyback route | A4 burn series | Issuance basis | "
          "Absorption emissions | Unlock stock |",
          "|---|---|---|---|---|---|---|---|---|"]
    for p in config.PROJECTS:
        n = p["name"]
        tot = "on-chain first" if n in config.TOTAL_SUPPLY_ONCHAIN_FIRST else "CoinGecko first"
        route = config.buyback_route(n)
        L.append(f"| {n} | {', '.join(str(a) for a in p.get('archetypes') or [])} | "
                 f"`{config.circulating_primary_metric(n)}` | {tot} | {route['route']} | "
                 f"`{config.a4_burn_metric(n)}` | `{config.issuance_basis(n)}` | "
                 f"{' + '.join(f'`{m}`' for m in config.absorption_emission_metrics(n))} | "
                 f"{' + '.join(f'`{m}`' for m in config.unlock_stock_metrics(n)) or '—'} |")
    return "\n".join(L) + "\n"


def flow_statements() -> list[str]:
    """TOKEN FLOW and VALUE FLOW STATEMENTS per project (Jake 2026-10-12, Phase 2 amendment 4): every flow in and out of
    circulating and every $ from customers to holders, each with the series that measures it — or NO SERIES, flagged."""
    import config
    ms_of = {p["name"]: set(config.metrics_for_project(p)) for p in config.PROJECTS}

    def ser(name, ms):
        ms = [m for m in ms if m]
        if not ms:
            return "**NO SERIES**"
        miss = [m for m in ms if m not in ms_of[name] and not m.startswith(("outflow_", "holder_value_"))]
        return " + ".join(f"`{m}`" for m in ms) + (f" (**not applicable here:** {', '.join(miss)})" if miss else "")
    L = ["---", "", "## Token flow and value flow statements (Phase 2, amendment 4)", "",
         "Per project: every flow INTO circulating (the five outflow categories, config OUTFLOW_CATEGORIES) and OUT of "
         "it (retirement, burn), then the value chain from customers to holders (fees -> the project's revenue basis -> "
         "holder value, funding-aware, config HOLDER_VALUE). A flow with no series is flagged **NO SERIES**. Attributes "
         "(destination, certainty, capture status) are on the CP tab, from phase2_attributes.json. GEODNET is held "
         "(Jake: wait for the CL output).", ""]
    for p in config.PROJECTS:
        n = p["name"]
        oc = config.OUTFLOW_CATEGORIES.get(n)
        hv = config.HOLDER_VALUE.get(n) or {}
        if not oc and n not in config.PHASE2_ATTRIBUTES:
            continue
        L += [f"### {n}", "", "**Token flow statement**", "", "| Flow | Category | Series |", "|---|---|---|"]
        for c, nm in config.OUTFLOW_CATEGORY_NAMES.items():
            L.append(f"| into circulating | ({c}) {nm} | {ser(n, config.outflow_metrics(n, c))} |")
        bb = "retired_buyback_tokens" if "actual_buyback_tokens" in ms_of[n] else None
        L.append(f"| out of circulating | retirement (bought, burned + held) | {ser(n, [bb])} |")
        bm = config.a1_burn_metric(n)
        L.append(f"| out of circulating | burn (every burn) | {ser(n, [bm] if bm in ms_of[n] else [])} |")
        if (oc or {}).get("basis"):
            L += ["", f"Basis: {oc['basis']}"]
        if (oc or {}).get("pending"):
            L += ["", f"PENDING: {oc['pending']}"]
        L += ["", "**Value flow statement**", "", "| Step | Series |", "|---|---|"]
        rb = config.revenue_base_metric(n)
        L.append(f"| customers pay (gross fees) | {ser(n, ['fees_usd'] if 'fees_usd' in ms_of[n] else [])} |")
        L.append(f"| the project's revenue basis | {ser(n, [rb] if rb in ms_of[n] else [])} |")
        L.append(f"| bought back ($, every funding source) | "
                 f"{ser(n, ['actual_buyback_usd'] if 'actual_buyback_usd' in ms_of[n] else [])} |")
        L.append(f"| paid to holders, not bought | {ser(n, list(hv.get('distributed_extra') or ()))} |")
        L.append(f"| holder value CREDITED (revenue-funded) | "
                 f"{ser(n, ['holder_value_revenue_usd'] if 'holder_value_revenue_usd' in ms_of[n] else [])} |")
        fund = "; ".join(f"{a}..{b or 'now'} {f}: {w}" for a, b, f, w in hv.get("funding") or ())
        L += ["", f"Funding: {fund or 'revenue (the default: the programme documented base)'}", ""]
    return L


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    heads = headlines(captured_columns())
    miss = missing_entries(heads)
    if miss:
        print("NO DICTIONARY ENTRY for: " + "; ".join(miss))
        return 1
    text = render(heads)
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("METRICS.md is stale — run python generate_metrics_doc.py")
            return 1
        print("METRICS.md is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.name}: {sum(len(v) for v in heads.values())} column(s)")
    return 0


if __name__ == "__main__":
    import progress                                    # stdout line-buffered when piped (2026-10-11)
    progress.line_buffered()
    sys.exit(main())
